const now = new Date();
const day = 24 * 60 * 60 * 1000;
const at = (offsetDays: number, hour = 9, minute = 0) => {
  const d = new Date(now.getTime() + offsetDays * day);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};
